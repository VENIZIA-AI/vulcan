const MUST_READ = '## Must read first';

/** A block `vulcan sync` writes into AGENTS.md between its own markers, `<!-- vulcan:<name>:start ... -->` to `<!-- vulcan:<name>:end -->`. */
export class GeneratedBlock {
  static markersOf(opts: { name: string; origin: string }): { start: string; end: string } {
    return {
      start: `<!-- vulcan:${opts.name}:start - generated by vulcan sync from ${opts.origin}; do not edit -->`,
      end: `<!-- vulcan:${opts.name}:end -->`,
    };
  }

  /**
   * Puts the block into AGENTS.md: rewritten between its markers when it is there, else inserted
   * before the section that follows "Must read first", else appended. Text outside is never touched.
   */
  static merge(opts: { text: string; block: string; name: string }): {
    changed: boolean;
    text: string;
  } {
    const startPrefix = `<!-- vulcan:${opts.name}:start`;
    const endMarker = `<!-- vulcan:${opts.name}:end -->`;
    const start = opts.text.indexOf(startPrefix);
    const end = opts.text.indexOf(endMarker);
    let text: string;

    if (opts.text === '') {
      text = opts.block;
    } else if (start !== -1 && end > start) {
      text = `${opts.text.slice(0, start)}${opts.block.trimEnd()}${opts.text.slice(end + endMarker.length)}`;
    } else {
      const heading = opts.text.indexOf(MUST_READ);
      // The section that follows, or another generated block, whichever comes first.
      const nexts =
        heading === -1
          ? []
          : ['\n## ', '\n<!-- vulcan:']
              .map((marker) => opts.text.indexOf(marker, heading + MUST_READ.length))
              .filter((at) => at !== -1);
      const next = nexts.length === 0 ? -1 : Math.min(...nexts);

      if (next === -1) {
        text = `${opts.text}${opts.text.endsWith('\n') ? '' : '\n'}\n${opts.block}`;
      } else {
        const at = next + 1;

        text = `${opts.text.slice(0, at)}${opts.block}\n${opts.text.slice(at)}`;
      }
    }

    return { changed: text !== opts.text, text };
  }
}

import { describe, expect, test } from 'bun:test';
import { AgentSignature, CommitAgents } from '../../commit/index.ts';
import type { ICommentStyle } from '../../commit/index.ts';

const find = (opts: {
  message: string;
  extra?: string[];
  allow?: string[];
  comment?: ICommentStyle;
}): string[] =>
  AgentSignature.find({
    message: opts.message,
    agents: CommitAgents.read({ extra: opts.extra ?? [], allow: opts.allow }),
    comment: opts.comment,
  }).map((hit) => hit.text);

describe('a trailer or a generated line that names an agent is a signature', () => {
  const REJECTED = [
    'Co-Authored-By: Claude <noreply@anthropic.com>',
    'Co-authored-by: Claude Opus 4.5 <noreply@anthropic.com>',
    'Co-Authored-By: GPT-5 <noreply@openai.com>',
    'Co-authored-by: Codex <codex@users.noreply.github.com>',
    'Co-authored-by: gemini-code-assist[bot] <176961590+gemini-code-assist[bot]@users.noreply.github.com>',
    'Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>',
    'Co-authored-by: Cursor Agent <cursoragent@cursor.com>',
    'Co-authored-by: Some Tool <noreply@google.com>',
    'Co-authored-by: Some Tool <no-reply@anthropic.com>',
    'Co-authored-by: Some Tool <noreply@mail.openai.com>',
    'Signed-off-by: Claude <noreply@anthropic.com>',
    '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    'Generated with Claude Code',
    'Generated by Codex',
    '⚙️ Generated with Claude',
    'Generated with Cl\u200Baude',
    'Co-Authored-By: ClaudeCode <bot@example.com>',
    'Co-Authored-By: OpenAICodex <bot@example.com>',
    'Co-Authored-By: ChatGPT4 <x@example.com>',
    'Co-Authored-By: Cl\u200Baude Code <x@example.com>',
    'Co-developed-by: Claude <noreply@anthropic.com>',
    'Assisted-by: Claude Opus',
    'Reviewed-by: Claude <noreply@anthropic.com>',
    'Co\u2011Authored\u2011By: Claude <noreply@anthropic.com>',
    'Co-Authored-By:  Bot <noreply@anthropic.com>',
    'Co-Authored-By: Bot <no_reply@anthropic.com>',
    'Co-Authored-By: Bot <noreply@ANTHROPIC.COM>',
  ];

  for (const line of REJECTED) {
    test(`rejects: ${line}`, () => {
      expect(find({ message: `fix(sync): a thing\n\n${line}\n` })).toEqual([line]);
    });
  }

  test('a CRLF message is read line by line, so a trailer ends at the line break', () => {
    const message = 'fix: a\r\n\r\nCo-Authored-By: Claude <noreply@anthropic.com>\r\n';

    expect(find({ message })).toEqual(['Co-Authored-By: Claude <noreply@anthropic.com>']);
  });

  test('a last line that ends in a bare carriage return is read too', () => {
    expect(
      find({ message: 'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\r' }),
    ).toHaveLength(1);
  });

  test('reports the line of each signature in a message with two', () => {
    const hits = AgentSignature.find({
      message:
        'fix: a\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nGenerated with Claude Code\n',
      agents: CommitAgents.read({ extra: [] }),
    });

    expect(hits.map((hit) => hit.line)).toEqual([3, 4]);
  });
});

describe('everything else passes', () => {
  const ACCEPTED = [
    'Co-authored-by: Jane Doe <jane@example.dev>',
    'Co-authored-by: Nguyen Van A <a@gmail.com>',
    'Co-authored-by: Jane <jane@anthropic.com>',
    'Co-authored-by: Jane <noreply@example.dev>',
    'Signed-off-by: Jane Doe <jane@example.dev>',
    'Generated with protoc',
    'generated with [a tool](https://example.dev)',
    'Generated by [the release script](link)',
    'Co-Authored-By: Claude Dupont <claude.dupont@example.fr>',
    'Co-Authored-By: Jane (Cursor team) <jane@cursor.sh>',
    'Co-Authored-By: Bot <x@users.noreply.github.com>',
    'The migration is generated with the schema tool',
    '# Co-Authored-By: Claude <noreply@anthropic.com>',
    '',
  ];

  for (const line of ACCEPTED) {
    test(`accepts: ${line === '' ? '(an empty line)' : line}`, () => {
      expect(find({ message: `fix(sync): a thing\n\n${line}\n` })).toEqual([]);
    });
  }

  test('a tool named in the subject is not a signature', () => {
    expect(
      find({ message: '[#12] fix(sync): merge the Claude settings with the project ones\n' }),
    ).toEqual([]);
  });
});

describe('git commit -v puts the diff below a scissors line', () => {
  const SCISSORS = '# ------------------------ >8 ------------------------';

  test('what is below it is not read, what is above it is', () => {
    const diff = '+Co-Authored-By: Claude <noreply@anthropic.com>\n+Generated with Claude Code';

    expect(find({ message: `fix: a\n\n${SCISSORS}\n${diff}\n` })).toEqual([]);
    expect(
      find({
        message: `fix: a\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n${SCISSORS}\n${diff}\n`,
      }),
    ).toEqual(['Co-Authored-By: Claude <noreply@anthropic.com>']);
  });
});

describe('a project adds names to the shipped list', () => {
  test('an extra name is matched as a whole word, in any case', () => {
    const message = 'fix: a\n\nCo-authored-by: WindSurf <bot@windsurf.dev>\n';

    expect(find({ message })).toEqual([]);
    expect(find({ message, extra: ['windsurf'] })).toEqual([
      'Co-authored-by: WindSurf <bot@windsurf.dev>',
    ]);
  });

  test('an extra name cannot remove a shipped one', () => {
    expect(CommitAgents.read({ extra: ['windsurf'] }).products).toContain('claude code');
    expect(CommitAgents.read({ extra: ['windsurf'] }).mentions).toContain('claude');
  });

  test('a name on the allow list is never flagged', () => {
    const message = 'fix: a\n\nCo-Authored-By: Claude Opus Dupont <claude.opus@example.fr>\n';

    expect(find({ message })).toHaveLength(1);
    expect(find({ message, allow: ['Claude Opus Dupont'] })).toEqual([]);
  });
});

describe("an allowed name is a whole name with an address that is not an agent's", () => {
  const CODE = 'fix: a\n\nCo-Authored-By: Claude Code <person@example.fr>\n';

  test('allow Claude does not clear a product form', () => {
    expect(find({ message: CODE, allow: ['Claude'] })).toHaveLength(1);
  });

  test('allow Claude Code clears exactly that name', () => {
    expect(find({ message: CODE, allow: ['Claude Code'] })).toEqual([]);
    expect(find({ message: CODE, allow: ['claude-code'] })).toEqual([]);
  });

  test('an allowed name with an agent address is still flagged', () => {
    const message = 'fix: a\n\nCo-Authored-By: Claude Code <noreply@anthropic.com>\n';

    expect(find({ message, allow: ['Claude Code'] })).toHaveLength(1);
  });
});

describe('a local part names an agent only at a domain an agent uses', () => {
  test('claude@martin.fr is a person, claude@anthropic.com and cursoragent@cursor.com are not', () => {
    expect(find({ message: 'x\n\nCo-Authored-By: Claude Martin <claude@martin.fr>\n' })).toEqual(
      [],
    );
    expect(find({ message: 'x\n\nCo-Authored-By: Tool <claude@anthropic.com>\n' })).toHaveLength(1);
    expect(find({ message: 'x\n\nCo-Authored-By: Tool <cursoragent@cursor.com>\n' })).toHaveLength(
      1,
    );
    expect(
      find({ message: 'x\n\nCo-Authored-By: Tool <codex@users.noreply.github.com>\n' }),
    ).toHaveLength(1);
  });
});

describe('a product matches whole words', () => {
  const people = [
    'Claude Coderre <c@example.fr>',
    'Gpta Rao <g@example.fr>',
    'Anthropic-fan Bob <b@example.fr>',
    'Codexa Smith <s@example.fr>',
    'Copilotte Durand <d@example.fr>',
  ];

  for (const person of people) {
    test(`passes: ${person}`, () => {
      expect(find({ message: `x\n\nCo-Authored-By: ${person}\n` })).toEqual([]);
    });
  }

  for (const tool of [
    'Claude Code 4 <x@example.com>',
    'GPT-5 <x@example.com>',
    'Claude-Code <x@example.com>',
  ]) {
    test(`rejects: ${tool}`, () => {
      expect(find({ message: `x\n\nCo-Authored-By: ${tool}\n` })).toHaveLength(1);
    });
  }
});

describe('a generated line names an agent right after the phrase', () => {
  for (const note of [
    'Generated by scripts/gen.ts from CLAUDE.md',
    'Generated with the cursor-based paginator',
    'Generated with protoc-gen-go',
  ]) {
    test(`passes: ${note}`, () => {
      expect(find({ message: `x\n\n${note}\n` })).toEqual([]);
    });
  }

  for (const note of [
    'Generated with Claude Code (opus)',
    'Generated by [Claude Code](https://claude.com/claude-code)',
    '**Generated with Cursor Agent**',
  ]) {
    test(`rejects: ${note}`, () => {
      expect(find({ message: `x\n\n${note}\n` })).toHaveLength(1);
    });
  }
});

describe('the comment character of the repository', () => {
  const signed = 'Co-Authored-By: Claude <noreply@anthropic.com>';

  test('with core.commentChar set, its lines are comments and a # line is not', () => {
    const comment: ICommentStyle = { prefixes: [';'] };

    expect(find({ message: `x\n\n;${signed}\n`, comment })).toEqual([]);
    expect(find({ message: `x\n\n${signed}\n`, comment })).toHaveLength(1);
  });

  test('its scissors line cuts the message too', () => {
    const comment: ICommentStyle = { prefixes: [';'] };
    const message = `x\n\n; ------------------------ >8 ------------------------\n${signed}\n`;

    expect(find({ message, comment })).toEqual([]);
    expect(find({ message })).toHaveLength(1);
  });

  test('with auto, any character git may pick is a comment', () => {
    const comment: ICommentStyle = { prefixes: ['#', ';', '@', '!', '$', '%', '^', '&', '|', ':'] };

    expect(find({ message: `x\n\n@${signed}\n`, comment })).toEqual([]);
    expect(
      find({
        message: `x\n\n@ ------------------------ >8 ------------------------\n${signed}\n`,
        comment,
      }),
    ).toEqual([]);
  });
});

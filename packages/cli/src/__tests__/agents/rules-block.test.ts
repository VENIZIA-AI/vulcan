import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { AtlasBlock, GeneratedBlock, RulesBlock } from '../../agents/index.ts';
import { BASE_DIRECTORY } from '../../common/index.ts';
import { ConfigConstants } from '../../config/index.ts';
import { RulePacks, RuleParser, RuleSlots } from '../../rules/index.ts';

const row = (id: string, text: string): string => `| ${id} | ${text} | SOFT |`;

const BASE_ROWS = [
  ...RuleParser.extractRows({ markdown: readFileSync(join(BASE_DIRECTORY, 'rules.md'), 'utf8') }),
  ...Object.values(RulePacks.rowsOf({ name: 'venizia' })),
];

describe('RulesBlock.summaryOf', () => {
  test('a rule is its first sentence, plain; a title alone takes the next sentence', () => {
    expect(
      RulesBlock.summaryOf({
        row: row(
          'V-P-07',
          '**Facts come from atlas, not memory.** Before you use an API, look it up.',
        ),
      }),
    ).toBe('Facts come from atlas, not memory. Before you use an API, look it up.');
    expect(
      RulesBlock.summaryOf({
        row: row(
          'V-W-02',
          'Never write to a database. Write the migration file, hand over. SELECT ok.',
        ),
      }),
    ).toBe('Never write to a database. Write the migration file, hand over.');
    expect(
      RulesBlock.summaryOf({
        row: row(
          'V-B-03',
          'Run it, read real output, then claim the result of the work. More text here.',
        ),
      }),
    ).toBe('Run it, read real output, then claim the result of the work.');
  });

  test('a long first sentence is kept whole, never cut', () => {
    const sentence = `${'word '.repeat(60)}end.`;
    const summary = RulesBlock.summaryOf({ row: row('V-C-09', `${sentence} Second sentence.`) });

    expect(summary).toBe(sentence);
    expect(summary).not.toContain('**');
  });
});

test('the block may weigh 6 KB: the owner chose it, Claude Code gives a hook up to about 10,000 bytes', () => {
  expect(RulesBlock.MAX_BYTES).toBe(6144);
});

describe('RulesBlock.render', () => {
  const rows = [
    row('V-W-02', 'Never write to a database. Write the migration file.'),
    row('V-W-03', 'Never deploy or hot-apply (kubectl apply).'),
    row('V-W-06', 'Approval has a card. Shared writes follow four action classes.'),
    row('V-P-07', 'Facts come from atlas, not memory, before you write any code of this project.'),
    row('V-B-03', 'Run it, read real output, then claim. Evidence before assertions.'),
  ];
  const input = {
    rows,
    slotLines: ['- V-W-01: this project: `on-user-word` - Git writes happen on the word.'],
    tmp: '.agents/local/tmp',
    oftenDropped: ['V-P-07', 'V-B-03', 'V-X-99'],
  };

  test('is marked as generated, and holds the slot, the write boundaries, the temp folder and the often-dropped rules', () => {
    const block = RulesBlock.render(input);

    expect(block.startsWith('<!-- vulcan:rules:start - generated by vulcan sync')).toBe(true);
    expect(block.trimEnd().endsWith('<!-- vulcan:rules:end -->')).toBe(true);
    expect(block).toContain('- V-W-01: this project: `on-user-word`');
    for (const id of ['V-W-02', 'V-W-03', 'V-W-06', 'V-P-07', 'V-B-03']) {
      expect(block, id).toContain(`- ${id}: `);
    }
    expect(block).toContain('go in `.agents/local/tmp`, never /tmp');
    expect(block).toContain('export TMPDIR="$PWD/.agents/local/tmp"');
  });

  test('an often-dropped ID that no rule file holds is left out, not printed empty', () => {
    expect(RulesBlock.render(input)).not.toContain('V-X-99');
  });

  test('over its budget, the often-dropped rules go from the last; the fixed part stays', () => {
    const long = 'x'.repeat(100);
    const many = Array.from(
      { length: 90 },
      (_unused, index) => `V-Z-${String(index).padStart(2, '0')}`,
    );
    const block = RulesBlock.render({
      ...input,
      rows: [...rows, ...many.map((id) => row(id, `${long}.`))],
      oftenDropped: ['V-P-07', ...many],
    });
    const kept = many.filter((id) => block.includes(`- ${id}: `));

    expect(Buffer.byteLength(block)).toBeLessThanOrEqual(RulesBlock.MAX_BYTES);
    expect(kept.length).toBeGreaterThan(0);
    expect(kept.length).toBeLessThan(many.length);
    expect(kept).toEqual(many.slice(0, kept.length));
    expect(block).toContain('- V-P-07: ');
    expect(block).toContain('- V-W-06: ');
    expect(block).toContain('export TMPDIR=');
  });

  test('a pack the project follows is named with its file and its rule IDs', () => {
    const block = RulesBlock.render({
      ...input,
      packs: [
        {
          name: 'venizia',
          path: 'node_modules/@venizia/vulcan/base/packs/venizia.md',
          ids: ['V-B-05', 'V-C-08'],
        },
      ],
    });

    expect(block).toContain(
      '- Pack `venizia` (`node_modules/@venizia/vulcan/base/packs/venizia.md`): this project follows it - V-B-05, V-C-08.',
    );
    expect(RulesBlock.render(input)).not.toContain('- Pack ');
  });

  test('the real base rules and the default often-dropped list fit in the budget, whole', () => {
    const block = RulesBlock.render({
      rows: BASE_ROWS,
      slotLines: RulesBlock.slotLinesOf({
        slots: RuleSlots.read(),
        choices: { 'V-W-01': 'on-user-word' },
        command: 'bun x --no-install vulcan',
      }),
      tmp: '.agents/local/tmp',
      oftenDropped: [...ConfigConstants.DEFAULT_OFTEN_DROPPED],
    });

    expect(Buffer.byteLength(block)).toBeLessThanOrEqual(RulesBlock.MAX_BYTES);
    expect(block).toContain('- V-P-07: ');
    expect(block).toContain('- V-W-06: ');

    // Every default rule is there, and no line is cut.
    for (const id of ConfigConstants.DEFAULT_OFTEN_DROPPED) {
      expect(block, id).toContain(`- ${id}: `);
    }

    expect(block).not.toContain(' ...');
  });
});

describe('RulesBlock.slotLinesOf', () => {
  const slots = RuleSlots.read();
  const command = 'bun x --no-install vulcan';

  test('names the chosen option with its text, or says the project has not chosen, or that the option is unknown', () => {
    const chosen = RulesBlock.slotLinesOf({ slots, choices: { 'V-W-01': 'read-only' }, command });
    const none = RulesBlock.slotLinesOf({ slots, choices: {}, command });
    const unknown = RulesBlock.slotLinesOf({ slots, choices: { 'V-W-01': 'nonsense' }, command });

    expect(chosen[0]).toContain('- V-W-01: this project: `read-only` - ');
    expect(none[0]).toContain('not chosen');
    expect(none[0]).toContain(`run \`${command} doctor\``);
    expect(unknown[0]).toContain('unknown option');
  });
});

describe('GeneratedBlock.merge', () => {
  const TEXT = '# AGENTS.md\n\n## Must read first\n\n| a | b |\n\n## Commands\n\n| c | d |\n';
  const rules = RulesBlock.render({ rows: [], slotLines: [], tmp: 't', oftenDropped: [] });
  const atlas = AtlasBlock.render({ project: 'acme', sources: [] });

  test('a block lands before the section that follows "Must read first"', () => {
    const merged = RulesBlock.merge({ text: TEXT, block: rules });

    expect(merged.changed).toBe(true);
    expect(merged.text.indexOf('vulcan:rules:start')).toBeLessThan(
      merged.text.indexOf('## Commands'),
    );
    expect(merged.text.startsWith('# AGENTS.md\n\n## Must read first\n\n| a | b |')).toBe(true);
  });

  test('a second block lands before the first, not inside it, and a rerun changes nothing', () => {
    const withAtlas = AtlasBlock.merge({ text: TEXT, block: atlas }).text;
    const both = RulesBlock.merge({ text: withAtlas, block: rules });
    const again = RulesBlock.merge({ text: both.text, block: rules });

    expect(both.text.indexOf('vulcan:rules:end')).toBeLessThan(
      both.text.indexOf('vulcan:atlas:start'),
    );
    expect(both.text.indexOf('vulcan:atlas:start')).toBeLessThan(both.text.indexOf('## Atlas'));
    expect(again.changed).toBe(false);
    expect(AtlasBlock.merge({ text: both.text, block: atlas }).changed).toBe(false);
  });

  test('a block with its markers is rewritten in place and the text around it is kept', () => {
    const first = RulesBlock.merge({ text: TEXT, block: rules }).text;
    const next = RulesBlock.render({
      rows: [],
      slotLines: ['- V-W-01: changed'],
      tmp: 't',
      oftenDropped: [],
    });
    const merged = RulesBlock.merge({ text: first, block: next });

    expect(merged.text).toContain('- V-W-01: changed');
    expect(merged.text.match(/vulcan:rules:start/g)?.length).toBe(1);
    expect(merged.text.endsWith('| c | d |\n')).toBe(true);
  });

  test('markersOf names the block and where it came from', () => {
    expect(GeneratedBlock.markersOf({ name: 'x', origin: 'the config' })).toEqual({
      start: '<!-- vulcan:x:start - generated by vulcan sync from the config; do not edit -->',
      end: '<!-- vulcan:x:end -->',
    });
  });
});

import { describe, expect, test } from 'bun:test';
import {
  ATLAS_BLOCK_END,
  ATLAS_BLOCK_START,
  mergeAtlasBlock,
  renderAtlasBlock,
} from '../../agents/index.ts';

const BLOCK = renderAtlasBlock({ project: 'acme', sources: ['ignis', 'ardor'] });
const ROUTING = [
  '# AGENTS.md',
  '',
  'How to work in acme.',
  '',
  '## Must read first',
  '',
  '| Read | What |',
  '|---|---|',
  '| `rules.md` | the rules |',
  '',
  '## Commands',
  '',
  '| Command | What |',
  '',
].join('\n');

describe('renderAtlasBlock', () => {
  test('is marked as generated, names the corpora and the three triggers and cites V-P-07', () => {
    expect(BLOCK.startsWith(`${ATLAS_BLOCK_START}`)).toBe(true);
    expect(BLOCK.trimEnd().endsWith(ATLAS_BLOCK_END)).toBe(true);
    expect(BLOCK).toContain('generated by vulcan sync from .configs/vulcan.config.*; do not edit');
    expect(BLOCK).toContain('## Atlas');
    expect(BLOCK).toContain('acme (this repository), ignis, ardor');
    expect(BLOCK).toContain('(V-P-07)');
    expect(BLOCK).toContain(
      '`symbol` before you use an export (signature, import path, source line)',
    );
    expect(BLOCK).toContain(
      '`search`, then `get`, for how something works or which convention applies',
    );
    expect(BLOCK).toContain('`version` or `changes` for a release or an upgrade');
    expect(BLOCK).toContain(
      'A new app or package: ask `presets` which preset and which `vulcan add` command, run it, and never hand-write package.json, tsconfig or scripts.',
    );
    expect(BLOCK).toContain(
      'How to build something here (a feature, a controller, a service, a repository): `search` first, then `get`, before you answer; a plan never says "check atlas" for a step you have not done.',
    );
  });

  test('a project with no sources names only itself', () => {
    expect(renderAtlasBlock({ project: 'solo', sources: [] })).toContain('solo (this repository).');
  });

  test('is short: a heading and five lines of text between the markers', () => {
    const inner = BLOCK.split('\n').filter(
      (line) => line.trim() !== '' && !line.startsWith('<!--'),
    );

    expect(inner.length).toBeLessThanOrEqual(6);
  });
});

describe('mergeAtlasBlock', () => {
  test('inserts the block before the section after "Must read first"', () => {
    const merged = mergeAtlasBlock({ text: ROUTING, block: BLOCK });

    expect(merged.changed).toBe(true);
    expect(merged.text.indexOf('## Must read first')).toBeLessThan(
      merged.text.indexOf(ATLAS_BLOCK_START),
    );
    expect(merged.text.indexOf(ATLAS_BLOCK_END)).toBeLessThan(merged.text.indexOf('## Commands'));
    expect(merged.text.replace(BLOCK, '').replace(/\n{3,}/g, '\n\n')).toBe(ROUTING);
  });

  test('without a "Must read first" section the block is appended', () => {
    const text = '# AGENTS.md\n\nhand written\n';
    const merged = mergeAtlasBlock({ text, block: BLOCK });

    expect(merged.text).toBe(`${text}\n${BLOCK}`);
  });

  test('an empty file gets just the block', () => {
    expect(mergeAtlasBlock({ text: '', block: BLOCK })).toEqual({ changed: true, text: BLOCK });
  });

  test('the same block again changes nothing', () => {
    const once = mergeAtlasBlock({ text: ROUTING, block: BLOCK }).text;

    expect(mergeAtlasBlock({ text: once, block: BLOCK })).toEqual({ changed: false, text: once });
  });

  test('a block for other corpora is rewritten between its markers, the hand-written text untouched', () => {
    const once = mergeAtlasBlock({ text: ROUTING, block: BLOCK }).text;
    const other = renderAtlasBlock({ project: 'acme', sources: ['ignis'] });
    const merged = mergeAtlasBlock({ text: once, block: other });

    expect(merged.changed).toBe(true);
    expect(merged.text).toContain('acme (this repository), ignis.');
    expect(merged.text).not.toContain('ardor');
    expect(merged.text.replace(other, '').replace(/\n{3,}/g, '\n\n')).toBe(ROUTING);
  });

  test('hand-written text around the block is kept byte for byte', () => {
    const text = `intro\n\n${BLOCK}\ntail line\n`;
    const other = renderAtlasBlock({ project: 'acme', sources: [] });
    const merged = mergeAtlasBlock({ text, block: other });

    expect(merged.text).toBe(`intro\n\n${other}\ntail line\n`);
  });
});

import { existsSync, readFileSync } from 'node:fs';
import { dirname, isAbsolute, relative, resolve, sep } from 'node:path';
import { z } from 'zod';
import { CreateConstants } from './common/index.ts';
import type { ILocatedPreset } from './common/index.ts';

/** `package.json` fields a lib preset may pass through; anything else it generates itself or does not support. */
const PACKAGE_FIELDS = ['type', 'sideEffects', 'browser', 'engines'];
const GENERATED_FIELDS: Record<string, string> = {
  name: 'name',
  version: 'version',
  private: 'private',
  exports: 'exports',
  imports: 'imports',
  scripts: 'scripts',
  dependencies: 'dependencies',
  devDependencies: 'devDependencies',
  peerDependencies: 'peerDependencies',
};

const LIB_SCHEMA = z
  .strictObject({
    presetVersion: z.number(),
    summary: z.string(),
    dependencies: z.record(z.string(), z.string()).default({}),
    devDependencies: z.record(z.string(), z.string()).default({}),
    peerDependencies: z.record(z.string(), z.string()).default({}),
    scripts: z.record(z.string(), z.string()).default({}),
    checks: z.array(z.string()).default([]),
    imports: z.record(z.string(), z.string()).default({}),
    exports: z.record(z.string(), z.unknown()).default({}),
    packageFields: z.record(z.string(), z.unknown()).default({}),
    files: z.string(),
    atlas: z.array(z.object({ name: z.string(), repo: z.string(), ref: z.string() })).default([]),
  })
  .superRefine((value, context) => {
    value.checks.forEach((check, index) => {
      if (!Object.hasOwn(value.scripts, check)) {
        context.addIssue({
          code: 'custom',
          path: ['checks', index],
          message: `"${check}" is not a key of scripts`,
        });
      }
    });

    for (const key of Object.keys(value.imports)) {
      if (!key.startsWith('#')) {
        context.addIssue({
          code: 'custom',
          path: ['imports', key],
          message: `"${key}" is not a subpath import: a key starts with #`,
        });
      }
    }

    for (const key of Object.keys(value.packageFields)) {
      const generated = GENERATED_FIELDS[key];

      if (generated !== undefined) {
        context.addIssue({
          code: 'custom',
          path: ['packageFields', key],
          message: `is generated by vulcan - declare it in ${generated} instead`,
        });
      } else if (!PACKAGE_FIELDS.includes(key)) {
        context.addIssue({
          code: 'custom',
          path: ['packageFields', key],
          message: `is not allowed - one of: ${PACKAGE_FIELDS.join(', ')}`,
        });
      }
    }
  });

export type TLibPreset = Omit<z.infer<typeof LIB_SCHEMA>, 'files'> & {
  /** The folder holding the files to copy, absolute. */
  files: string;
};

export type TLibPresetResult = { ok: true; lib: TLibPreset } | { ok: false; error: string };

const escapes = (opts: { root: string; path: string }): boolean => {
  const relativePath = relative(opts.root, opts.path);

  return isAbsolute(relativePath) || relativePath === '..' || relativePath.startsWith(`..${sep}`);
};

/** The lib preset of a located preset package, validated; the app side is never touched by an error here. */
export const readLibPreset = (opts: { located: ILocatedPreset }): TLibPresetResult => {
  const { located } = opts;
  const shown = `${located.packageName}@${located.packageVersion}`;
  const file = located.libFile;

  if (file === undefined) {
    return { ok: false, error: `preset ${located.packageName} has no lib kind` };
  }

  let raw: unknown;

  try {
    raw = JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    return { ok: false, error: `${shown}: ${file} is missing or not JSON` };
  }

  if (
    typeof raw !== 'object' ||
    raw === null ||
    !('presetVersion' in raw) ||
    raw.presetVersion !== CreateConstants.PRESET_VERSION
  ) {
    return {
      ok: false,
      error: `${shown}: the lib preset has preset version ${String(typeof raw === 'object' && raw !== null && 'presetVersion' in raw ? raw.presetVersion : undefined)}; this VULCAN reads version ${CreateConstants.PRESET_VERSION} - upgrade @venizia/vulcan`,
    };
  }

  const parsed = LIB_SCHEMA.safeParse(raw);

  if (!parsed.success) {
    const issues = parsed.error.issues
      .map(issue => `${issue.path.join('.')} ${issue.message}`)
      .join('; ');

    return { ok: false, error: `${shown}: lib preset: ${issues}` };
  }

  const files = resolve(dirname(file), parsed.data.files);

  if (escapes({ root: located.packageRoot, path: files }) || !existsSync(files)) {
    return {
      ok: false,
      error: `${shown}: lib preset: files ${parsed.data.files} is missing or points outside the package`,
    };
  }

  return { ok: true, lib: { ...parsed.data, files } };
};

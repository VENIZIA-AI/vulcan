import { afterAll, describe, expect, test } from 'bun:test';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSyncBounded } from '../../__tests__/spawn.helper.ts';
import { signaturesOf } from '../check-agent-signature.ts';

const ROOT = join(import.meta.dir, '..', '..', '..');
const SCRIPT = join(ROOT, 'scripts', 'checks', 'check-agent-signature.ts');
const HOOK = join(ROOT, '.githooks', 'commit-msg');
const folders: string[] = [];
const ROBOT = String.fromCodePoint(0x1f916);

afterAll(() => {
  for (const folder of folders) {
    rmSync(folder, { recursive: true, force: true });
  }
});

const scratch = (): string => {
  const folder = mkdtempSync(join(tmpdir(), 'vulcan-signature-'));

  folders.push(folder);

  return folder;
};

const run = (opts: { cmd: string[]; cwd?: string }) => {
  const result = spawnSyncBounded({
    cmd: opts.cmd,
    cwd: opts.cwd,
    stdout: 'pipe',
    stderr: 'pipe',
  });

  return { code: result.exitCode, out: result.stdout.toString(), err: result.stderr.toString() };
};

const git = (opts: { cwd: string; args: string[] }) =>
  run({
    cmd: ['git', '-c', 'user.name=t', '-c', 'user.email=t@example.com', ...opts.args],
    cwd: opts.cwd,
  });

describe('signaturesOf', () => {
  test.each([
    ['Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>'],
    ['co-authored-by: Claude Sonnet 5.5 <noreply@anthropic.com>'],
    ['Co-Authored-By: GitHub Copilot <copilot@github.com>'],
    ['Co-Authored-By: Codex <codex@openai.com>'],
    ['Signed-off-by: Gemini CLI'],
    [`${ROBOT} Generated with [Claude Code](https://claude.com/claude-code)`],
    ['Generated with Claude Code'],
    ['generated by Codex'],
    ['Generated with [anything](https://example.com)'],
  ])('%s signs a commit as an agent', (line) => {
    const found = signaturesOf({ message: `[#1] feat(cli): a thing\n\nBody.\n\n${line}\n` });

    expect(found).toHaveLength(1);
    expect(found[0]?.line).toBe(5);
  });

  test.each([
    ['[#1] fix(cli): merge the Claude settings over the personal ones'],
    ['Co-Authored-By: Phat Nguyen <phat@example.com>'],
    ['Signed-off-by: Phat Nguyen <phat@example.com>'],
    ['Generated with protoc 27'],
    ['generated by the release script'],
    ['# Co-Authored-By: Claude <noreply@anthropic.com>'],
    ['Closes #12'],
  ])('%s is not a signature', (line) => {
    expect(signaturesOf({ message: `${line}\n` })).toEqual([]);
  });

  test('every signed line is named, by its line number', () => {
    const message =
      'subject\n\nCo-Authored-By: Claude <a@anthropic.com>\nGenerated with Claude Code\n';

    expect(signaturesOf({ message }).map((hit) => hit.line)).toEqual([3, 4]);
  });
});

describe('the command', () => {
  test('a clean message file passes and a signed one fails naming the line', () => {
    const folder = scratch();
    const clean = join(folder, 'clean');
    const signed = join(folder, 'signed');

    writeFileSync(clean, '[#1] docs: a change\n');
    writeFileSync(
      signed,
      '[#1] docs: a change\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n',
    );

    expect(run({ cmd: [process.execPath, SCRIPT, clean] }).code).toBe(0);

    const failed = run({ cmd: [process.execPath, SCRIPT, signed] });

    expect(failed.code).toBe(1);
    expect(failed.err).toContain('line 3');
    expect(failed.err).toContain('W-00');
  });

  test('--text checks one message and no arguments is a usage error', () => {
    expect(run({ cmd: [process.execPath, SCRIPT, '--text', 'a plain subject'] }).code).toBe(0);
    expect(
      run({ cmd: [process.execPath, SCRIPT, '--text', 'Generated with Claude Code'] }).code,
    ).toBe(1);
    expect(run({ cmd: [process.execPath, SCRIPT] }).code).toBe(2);
  });

  test('--range names the commit that carries a signature and only that one', () => {
    const folder = scratch();

    git({ cwd: folder, args: ['init', '-q', '-b', 'main'] });
    git({ cwd: folder, args: ['commit', '-q', '--allow-empty', '-m', 'base'] });
    git({ cwd: folder, args: ['commit', '-q', '--allow-empty', '-m', '[#1] a clean commit'] });
    git({
      cwd: folder,
      args: [
        'commit',
        '-q',
        '--allow-empty',
        '-m',
        '[#2] a signed commit',
        '-m',
        'Co-Authored-By: Claude <noreply@anthropic.com>',
      ],
    });

    const failed = run({ cmd: [process.execPath, SCRIPT, '--range', 'HEAD~2..HEAD'], cwd: folder });
    const head = git({ cwd: folder, args: ['rev-parse', '--short', 'HEAD'] }).out.trim();
    const parent = git({ cwd: folder, args: ['rev-parse', '--short', 'HEAD~1'] }).out.trim();

    expect(failed.code).toBe(1);
    expect(failed.err).toContain(`commit ${head}`);
    expect(failed.err).not.toContain(`commit ${parent}`);
    expect(
      run({ cmd: [process.execPath, SCRIPT, '--range', 'HEAD~2..HEAD~1'], cwd: folder }).code,
    ).toBe(0);
    expect(
      run({ cmd: [process.execPath, SCRIPT, '--range', 'HEAD..HEAD'], cwd: folder }).code,
    ).toBe(0);
  });
});

describe('the commit-msg hook', () => {
  test('refuses a commit that signs as an agent and lets a clean one through, in a real repository', () => {
    const folder = scratch();

    git({ cwd: folder, args: ['init', '-q', '-b', 'main'] });
    // The hook finds the script in the repository it runs in, so the scratch repository gets both and no other hook.
    mkdirSync(join(folder, '.githooks'));
    mkdirSync(join(folder, 'scripts', 'checks'), { recursive: true });
    copyFileSync(HOOK, join(folder, '.githooks', 'commit-msg'));
    copyFileSync(SCRIPT, join(folder, 'scripts', 'checks', 'check-agent-signature.ts'));
    run({ cmd: ['chmod', '+x', join(folder, '.githooks', 'commit-msg')] });
    git({ cwd: folder, args: ['config', 'core.hooksPath', '.githooks'] });

    const refused = git({
      cwd: folder,
      args: ['commit', '-q', '--allow-empty', '-m', 'a change', '-m', 'Generated with Claude Code'],
    });
    const allowed = git({ cwd: folder, args: ['commit', '-q', '--allow-empty', '-m', 'a change'] });

    expect(refused.code).not.toBe(0);
    expect(refused.err).toContain('signs the commit as an agent');
    expect(allowed.code).toBe(0);
  });
});
